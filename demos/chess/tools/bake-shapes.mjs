// Sculpt the carved parts once and pack them into shapes.js.
import { writeFileSync } from "node:fs";
import { sculptAll } from "./sculpt.js";
const b64 = (a) => Buffer.from(a.buffer, a.byteOffset, a.byteLength).toString("base64");
const out = {};
let total = 0;
for (const [t, g] of Object.entries(sculptAll())) {
    if (g.positions.length / 3 > 65535) throw new Error("too big");
    out[t] = {
        pos: b64(Int16Array.from(g.positions, (v) => Math.round(v * 16384))),
        nor: b64(Int16Array.from(g.normals, (v) => Math.round(v * 32767))),
        ao: b64(Uint8Array.from(g.ao, (v) => Math.round(v * 255))),
        idx: b64(Uint16Array.from(g.indices)),
    };
    total += g.positions.length / 3;
    console.log(t, g.positions.length / 3, "verts", g.indices.length / 3, "tris");
}
const text = `// Generated by tools/bake-shapes.mjs from tools/sculpt.js. Do not edit.\nexport const SHAPES = ${JSON.stringify(out)};\n`;
writeFileSync(new URL("../shapes.js", import.meta.url), text);
console.log("total verts", total, "file KB", text.length >> 10);
