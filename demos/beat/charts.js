/** Which difficulty gets what, and the song each mechanic is first taught in. The order of SONGS is the story's order. */
export const DIFFS = ["easy", "normal", "hard"];
export const INTRO = { hold: "skank", roll: "kettle", swipe: "warts" };

/**
 * Compile one chart to note objects, all timing in seconds of song time.
 * With o.from/o.to/o.speed it follows arrange()'s slice, so practice loops line up.
 */
export function compile(song, diff, o = {}) {
    const a = arrange(song, o), def = CHARTS[song.id][diff], notes = [];
    for (const sec of a.sections) {
        const phrase = def[sec.name] ?? def[sec.key];
        if (!phrase) continue;
        const u = song.sections[sec.key].unit ?? song.unit, cu = def.unit ?? song.chartUnit ?? u;
        const bars = phrase.trim().split("|").map((s) => s.trim());
        for (let bi = 0; bi < sec.bars; bi++) {
            const text = bars[bi % bars.length];
            const row = parseLine(text, song.bar, cu, `${song.id}.${diff}.${sec.name}`);
            row.forEach((t, i) => {
                if (t === "." || t === "-") return;
                const step = sec.start + bi * song.bar + i;
                const m = /^([HRS]?)(\d+)(?::(\d+))?$/.exec(t);
                if (!m) throw new Error(`Bad chart token ${t} in ${song.id}.${diff}.${sec.name}`);
                const kind = m[1] === "H" ? "hold" : m[1] === "R" ? "roll" : m[1] === "S" ? "swipe" : "tap";
                const len = Number(m[3] ?? 0) * cu;
                for (const ch of m[2]) {
                    const lane = Number(ch) - 1;
                    if (lane >= def.heads) throw new Error(`${song.id}.${diff}: lane ${ch} but only ${def.heads} heads`);
                    notes.push({ step, lane, kind, time: step * a.stepDur, dur: len * a.stepDur, endStep: step + len, sec: sec.name });
                }
            });
        }
    }
    notes.sort((x, y) => x.time - y.time || x.lane - y.lane);
    // A long note lets go in time for the next note on its head.
    for (const n of notes) {
        if (n.kind !== "hold" && n.kind !== "roll") continue;
        const next = notes.find((m) => m !== n && m.lane === n.lane && m.time > n.time + 0.001);
        if (next && next.time - n.time - n.dur < 0.18) { n.dur = Math.max(0, next.time - n.time - 0.18); n.endStep = n.step + n.dur / a.stepDur; }
        if (n.dur < 0.22) { n.kind = "tap"; n.dur = 0; }
    }
    notes.forEach((n, i) => { n.id = i; n.kick = !!a.seq.kick[n.step]; n.snare = !!a.seq.snare[n.step]; });
    return { notes, arr: a, heads: def.heads, def };
}
