const CHARS = Object.keys(G), CELL = 72, SCALE = 3.4, FRAMES = CHARS.length, COLS = 12;
const INDEX = new Map(CHARS.map((c, i) => [c, i]));

/** Paint the sheet: frame i is glyph i, as a white fill over black ink; tint in draw. Two sheets, so ink and fill take colours separately. */
export function paintFont(game) {
    const draw = (name, ink, fill) => game.assets.paint(name, CELL, CELL, (p, f) => {
        const g = new Ink(p, f, FRAMES), [w, ...strokes] = G[CHARS[f]], ox = (CELL - w * SCALE) / 2, oy = 13 - 0.5;
        for (const s of strokes) {
            const pts = s.map(([x, y]) => [ox + x * SCALE, oy + y * SCALE]);
            if (ink) g.stroke(pts, 18, ink);
            if (fill) g.stroke(pts, 10.5, fill);
        }
    }, { frames: FRAMES, smooth: true, mipmaps: false });
    draw("glyphInk", "#ffffff", null);
    draw("glyphFill", null, "#ffffff");
}

const advance = (c) => (G[c] ? G[c][0] : 5.5) * SCALE + 18;
export function measure(str, size) {
    const k = size / CELL;
    let w = 0;
    for (const ch of str) w += advance(lookup(ch)) * k * 0.92;
    return w;
}
const lookup = (ch) => (G[ch] && ch !== "x" ? ch : ch === "×" ? "x" : ch.toUpperCase());

/**
 * Draw a line of letters. opts: size, color, ink, wave (per-letter bop height), phase, spread, wobble, shadow.
 * Coordinates are the centre of the line.
 */
export function letters(d, str, x, y, o = {}) {
    const size = o.size ?? 28, k = size / CELL, total = measure(str, size), ink = o.ink ?? "#1b1423", fill = o.color ?? "#fff7d6", wave = o.wave ?? 0, op = o.opacity ?? 1;
    const glyphs = [];
    let cx = x - total / 2 * (o.align === "left" ? 0 : o.align === "right" ? 2 : 1);
    if (o.align === "left") cx = x;
    if (o.align === "right") cx = x - total;
    let i = 0;
    for (const raw of str) {
        const ch = lookup(raw), adv = advance(ch) * k * 0.92;
        if (INDEX.has(ch)) {
            const bob = wave ? Math.sin((o.phase ?? 0) * Math.PI * 2 - i * 0.7) * wave : 0, tilt = o.wobble ? Math.sin(i * 2.1 + (o.phase ?? 0) * 6.28) * o.wobble : 0;
            glyphs.push({ f: INDEX.get(ch), x: cx + adv / 2, y: y + bob, rot: tilt, s: 1 + (o.pop ? o.pop * Math.max(0, Math.sin((o.phase ?? 0) * Math.PI - i * 0.14)) : 0) });
        }
        cx += adv;
        i++;
    }
    if (o.shadow) for (const g of glyphs) d.sprite("glyphInk", { frame: g.f, x: g.x + size * 0.05, y: g.y + size * 0.09, width: size * g.s, height: size * g.s, color: o.shadow, opacity: op, rot: g.rot });
    for (const g of glyphs) d.sprite("glyphInk", { frame: g.f, x: g.x, y: g.y, width: size * g.s, height: size * g.s, color: ink, opacity: op, rot: g.rot });
    for (const g of glyphs) d.sprite("glyphFill", { frame: g.f, x: g.x, y: g.y, width: size * g.s, height: size * g.s, color: Array.isArray(fill) ? fill[g.f % fill.length] : fill, opacity: op, rot: g.rot });
}
