// Photographs every building on the card colour and writes cards.js, the tray's art. Run after changing a model.
import { createServer } from "node:http";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { extname, join, resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const require = createRequire(resolve(root, "../../package.json"));
const { chromium } = require("playwright-core");
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript" };
const server = createServer(async (req, res) => {
    const path = new URL(req.url, "http://x").pathname;
    try { const body = await readFile(join(root, path === "/" ? "index.html" : path)); res.writeHead(200, { "content-type": TYPES[extname(path) || ".html"] ?? "application/octet-stream" }); res.end(body); }
    catch { res.writeHead(404); res.end(); }
});
await new Promise((r) => server.listen(0, "127.0.0.1", r));
const browser = await chromium.launch({ headless: true, channel: "chrome", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 400, height: 400 }, deviceScaleFactor: 1 });
page.on("pageerror", (e) => console.error(e.message));
await page.goto(`http://127.0.0.1:${server.address().port}/?paused`);
await page.waitForFunction(() => globalThis.__pogo?.current);
const url = await page.evaluate(async () => {
    const game = globalThis.__pogo, cols = 5, cell = 120;
    const order = ["cottage", "lane", "dock", "market", "wood", "farm", "mill", "yard", "smoke", "pub", "light", "wall", "garden"];
    const tune = { dock: { size: 2.0, h: 0.1 }, light: { size: 2.3, h: 0.6 }, mill: { size: 2.1, h: 0.42 }, wall: { size: 1.8, h: 0.1 }, lane: { size: 1.6, h: 0.06 }, cottage: { size: 1.75, h: 0.28, variant: 0 }, market: { size: 1.75, h: 0.18 }, smoke: { size: 1.9, h: 0.35 }, pub: { size: 1.8, h: 0.25 }, yard: { size: 1.8, h: 0.15 }, wood: { size: 1.75, h: 0.15 }, farm: { size: 1.75, h: 0.05 }, garden: { size: 1.7, h: 0.03 } };
    const out = document.createElement("canvas");
    out.width = cols * cell; out.height = 3 * cell;
    const g = out.getContext("2d");
    for (let i = 0; i < order.length; i++) {
        game.go("thumb", { type: order[i], ...tune[order[i]] });
        game.step(45);
        game.render?.(0);
        const data = game.screenshot();
        const img = new Image();
        await new Promise((res) => { img.onload = res; img.src = data; });
        const m = Math.min(img.width, img.height), sx = (img.width - m) / 2, sy = (img.height - m) / 2;
        g.drawImage(img, sx, sy, m, m, (i % cols) * cell, Math.floor(i / cols) * cell, cell, cell);
    }
    // Grade: pull saturation down and lift the shadows towards the card, leaving the card colour itself untouched.
    const px = g.getImageData(0, 0, out.width, out.height), D = px.data, bg = [255, 246, 228];
    for (let o = 0; o < D.length; o += 4) {
        const dist = Math.abs(D[o] - bg[0]) + Math.abs(D[o + 1] - bg[1]) + Math.abs(D[o + 2] - bg[2]);
        const w = Math.min(1, dist / 45), L = 0.3 * D[o] + 0.59 * D[o + 1] + 0.11 * D[o + 2];
        for (let a = 0; a < 3; a++) {
            const grey = D[o + a] + (L - D[o + a]) * 0.34, soft = grey + (bg[a] - grey) * 0.08;
            D[o + a] = D[o + a] + (soft - D[o + a]) * w;
        }
    }
    g.putImageData(px, 0, 0);
    return out.toDataURL("image/png");
});
await writeFile(join(root, "cards.js"), `// Generated by tools/bake-cards.mjs: 3D photographs of the models.\nexport const CARDS = ${JSON.stringify(url)};\n`);
console.log("cards.js", Math.round(url.length / 1024), "KB");
await browser.close();
server.close();
