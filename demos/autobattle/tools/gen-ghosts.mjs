// Builds ghosts.js: bot teams for each round, sorted weak to strong. Bots play a few generations against each other's banks.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { SHOPS, TRAIT_IDS } from "../data.js";
import { fight, newRun, settle, teamOf } from "../run.js";
import { battle, hashStr, rngOf } from "../sim.js";
import { newcomerTurn, sharpTurn } from "../ai.js";

const ROUNDS = 15, KEEP = 28, GENS = 3, RUNS = 340;
const A = ["Mr Biscuit", "Auntie Clamp", "Old Wobble", "Madame Trout", "Sir Crumbs", "Nana Gristle", "Uncle Fizz", "Big Doris", "Doctor Pudding", "Captain Mop", "Little Gerald", "Lady Sprocket", "Professor Lint", "Cousin Marge", "Baron Sock", "Mother Pickle"];
const B = ["Bargain Barn", "Critter Depot", "Pet Warehouse", "Fur Emporium", "Beast Boutique", "Animal Outlet", "Creature Kiosk", "Zoo Annex", "Pet Pantry", "Critter Corner", "Whisker Mart", "Scale & Tail"];
const name = (r) => `${A[r.int(A.length)]}'s ${B[r.int(B.length)]}`;

const empty = () => { const bank = []; for (let i = 0; i < ROUNDS; i++) bank.push([]); return bank; };
function seedBank() {
    // Generation zero: untrained shoppers, so the first bots have something weak to beat.
    const bank = empty();
    for (let s = 1; s <= 80; s++) {
        const r = rngOf(s * 7), run = newRun({ seed: s * 13 + 1, shop: "corner" });
        for (let round = 1; round < ROUNDS; round++) { newcomerTurn(run, r); bank[round].push({ pets: teamOf(run), gold: run.gold }); run.lives = 9; run.wins = 0; settle(run, "b"); }
    }
    return bank;
}
function strength(rows) {
    // Round robin against a sample of the same round.
    const n = rows.length, wins = new Array(n).fill(0);
    for (let i = 0; i < n; i++) for (let k = 0; k < 18; k++) { const j = (i + 1 + k * 3) % n; if (i === j) continue; const res = battle(rows[i], rows[j], (i * 977 + k) >>> 0); if (res.winner === "a") wins[i] += 1; else if (res.winner === "b") wins[j] += 1; }
    return wins;
}
function thin(rows, keep) {
    if (!rows.length) return rows;
    const w = strength(rows), order = rows.map((t, i) => [t, w[i]]).sort((a, b) => a[1] - b[1]).map((x) => x[0]);
    if (order.length <= keep) return order;
    const out = []; for (let i = 0; i < keep; i++) out.push(order[Math.round((i * (order.length - 1)) / (keep - 1))]);
    return out;
}
let bank = seedBank().map((rows) => thin(rows, KEEP));
for (let g = 0; g < GENS; g++) {
    const next = empty();
    for (let s = 0; s < RUNS; s++) {
        const seed = hashStr(g + 11, `ghost${s}`), focus = s % 3 === 0 ? null : [TRAIT_IDS[s % 12], TRAIT_IDS[(s * 5 + 2) % 12]];
        const run = newRun({ seed, shop: SHOPS[s % 6].id }), r = rngOf(seed);
        const newbie = s % 5 === 4;
        while (!run.over) {
            if (newbie) newcomerTurn(run, r); else sharpTurn(run, { focus });
            next[run.round].push({ pets: teamOf(run), gold: run.gold });
            const { res } = fight(run, bank); settle(run, res.winner);
            if (run.round >= ROUNDS - 1) break;
        }
    }
    bank = next.map((rows, i) => thin(rows.length ? rows : bank[i], g === GENS - 1 ? KEEP : KEEP * 2));
    console.log("gen", g, bank.map((r) => r.length).join(" "));
}
const nr = rngOf(4242);
for (const rows of bank) for (const t of rows) t.name = name(nr);
const lines = bank.map((rows) => `  [${rows.map((t) => JSON.stringify(t)).join(",\n   ")}]`).join(",\n");
const out = `// Generated by tools/gen-ghosts.mjs: bot teams by round, weak to strong. These are the opponents: every team is a bot.\nexport const GHOSTS = [\n${lines}\n];\n`;
writeFileSync(resolve(import.meta.dirname, "../ghosts.js"), out);
console.log("ghosts.js", (out.length / 1024) | 0, "KB");
