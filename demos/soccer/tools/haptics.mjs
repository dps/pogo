// What the hand gets: stages each moment through the real scene and lists the pulses fired.
import "../game.js";
const game = globalThis.__pogo;
game.restart("match", {}, { seed: 3 });
game.step(2);
const { sim } = game.match;
let pulses = []; const orig = game.haptics.pulse.bind(game.haptics);
game.haptics.pulse = (k, gap) => { pulses.push(Array.isArray(k) ? `[${k}]` : k); return orig(k, gap); };
const h = sim.humans[0]; let script = () => {};
game.data.autoplay = (s, hh) => script(s, hh);
sim.phase = "play"; sim.clock = 110;
// Keep the other goats out of the way so each moment is clean.
const clear = () => { for (const q of sim.goats) if (q !== h.goat && q.role !== 0) { q.x = (q.team ? 20 : -20) + q.idx; q.z = -12 + q.idx * 5; q.vx = q.vz = 0; q.cool = 5; } };
const run = (name, n, fn) => { pulses = []; script = fn ?? (() => {}); for (let i = 0; i < n; i++) { clear(); game.step(1); } console.log(name.padEnd(34), pulses.length ? pulses.join(" ") : "(nothing)"); };
const g = h.goat;
run("first touch, tap PASS", 6, (s, x) => { x.a = game.stepCount % 6 < 3; });
run("carry the ball, 1 s", 60, (s, x) => { x.a = false; x.mx = 1; });
let c = h.goat; c.x = 8; c.z = 2; sim.ball.owner = c; sim.goats[5].z = -3.6;
run("charge to full, 0.9 s", 54, (s, x) => { x.b = true; x.mx = 0.4; });
run("release: power shot", 3, (s, x) => { x.b = false; });
sim.goats[5].x = 40;
const reset = () => { if (game.match.st.goal) game.match.st.goal = null; sim.phase = "play"; sim.phaseT = 0; s0(); };
const s0 = () => { for (const q of sim.goats) { q.state = 0; q.t = 0; q.cool = 0; q.immune = 0; q.y = 0; q.noTouch = 0; } sim.ball.power = 0; sim.ball.hot = 0; };
reset();
const me = h.goat, o = sim.goats[8];
me.x = 0; me.z = 0; me.ang = Math.PI / 2; o.x = 2.8; o.z = 0; o.vx = 0; sim.ball.owner = o; sim.ball.x = 3.6; sim.ball.z = 0;
pulses = []; script = (s, x) => { x.mx = 1; x.mz = 0; x.b = true; }; game.step(14); script = (s, x) => { x.b = false; x.mx = 0; }; console.log("your headbutt lands".padEnd(34), pulses.join(" ") || "(nothing)", `victim state ${o.state}`);
game.step(30); reset();
const v = h.goat, a = sim.goats[9];
sim.ball.owner = v; v.x = 0; v.z = 6; a.x = -2.4; a.z = 6; a.ang = Math.PI / 2; a.cmd.mx = 1; a.cmd.mz = 0;
pulses = []; sim.startButt(a); game.step(1); a.cmd.mx = 1; game.step(14); console.log("you get butted".padEnd(34), pulses.join(" ") || "(nothing)", `state ${v.state}`);
game.step(60); reset();
const g2 = h.goat; g2.x = 16; g2.z = 1; sim.ball.owner = g2; sim.ball.x = 17; sim.ball.z = 1; sim.goats[5].x = 23.4; sim.goats[5].z = -3.8; sim.goats[5].state = 7; sim.goats[5].holdT = 99;
pulses = []; sim.kickShot(g2, 0.9, { x: 24, z: 3, y: 1 }); game.step(40);
console.log("your shot scores".padEnd(34), pulses.join(" "), `(score ${sim.score})`);
const hs = game.state().haptics;
console.log("state().haptics tail", JSON.stringify(hs).slice(-80));
console.log("errors", game.errors?.length ?? 0);
process.exit(0);
