// Checks the feel by counting what the hand would get in each situation.
import "../game.js";
import { hurt } from "../kart.js";
const game = globalThis.__pogo;
game.restart("race", { track: "aisle", cls: "trolley", racer: "pip" });
game.data.save.seen = { steer: 1, drift: 1, item: 1 };
const W = game.sim, k = W.player;
const orig = game.haptics.pulse.bind(game.haptics);
let pulses = [];
game.haptics.pulse = (kind, gap) => { pulses.push(typeof kind === "object" ? `[${kind}]` : kind); return orig(kind, gap); };
const hold = (fn, n) => { pulses = []; for (let i = 0; i < n; i++) { W.controls = { read(inp) { inp.steer = 0; inp.drift = false; inp.item = false; inp.brake = false; fn(inp); } }; game.step(1); } const p = pulses.slice(); return p; };
while (W.phase !== "race") game.step(1);
const slow = hold(() => {}, 30), summary = (p) => `${p.length} pulses in ${p.slice(0, 5).join(" ")}`;
console.log("purr, pulling away ", summary(slow));
hold(() => {}, 150);
console.log("purr, top speed    ", k.speed.toFixed(1), summary(hold(() => {}, 30)));
console.log("drift, first 0.5 s ", summary(hold((i) => { i.steer = -0.6; i.drift = true; }, 30)));
console.log("drift, charge 1.0+ ", k.charge.toFixed(2), summary(hold((i) => { i.steer = -0.6; i.drift = true; }, 30)));
hold((i) => { i.steer = -0.6; i.drift = true; }, 40);
console.log("drift, charged     ", k.charge.toFixed(2), "tier", k.tier, summary(hold((i) => { i.steer = -0.6; i.drift = true; }, 30)));
console.log("release: boost     ", summary(hold(() => {}, 6)));
hold(() => {}, 90);
k.x += W.T.rx[k.i] * (W.T.hw[k.i] + 1.6); k.z += W.T.rz[k.i] * (W.T.hw[k.i] + 1.6);
console.log("gravel, off-track  ", k.d.toFixed(1), summary(hold(() => {}, 24)));
k.safe = 0; k.spin = 0;
pulses = []; hurt(k, "tumble"); W.drain(k); W.strike(k, { kind: "melon", owner: W.karts[0], x: k.x, y: k.y, z: k.z });
k.safe = 0; W.strike(k, { kind: "melon", owner: W.karts[0], x: k.x, y: k.y, z: k.z });
console.log("melon hit          ", pulses.join(" "));
process.exit(0);
